filmTuple = ('Inception', 'UP', 'The Dark Knight', 'Pulp Fiction', 'Interstellar')

print(type(filmTuple))

# 1 - Buscar os 2 primeiros itens da tupla
print(filmTuple[:2])

# 2 - Busca o ultimo item da tupla
print(filmTuple[-1])

# 3 - Busca filme de um intervalo especifico
print(filmTuple[2:5])

# 4 - Recuperar um item da tupla pelo nome
print(filmTuple.index('UP'))